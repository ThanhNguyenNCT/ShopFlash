-- Schema SHOP. User, tablespace và quyền được tạo trước bởi db/oracle-init (không thuộc Flyway).

CREATE TABLE users (
  user_id       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  email         VARCHAR2(255) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  full_name     VARCHAR2(150) NOT NULL,
  phone         VARCHAR2(30),
  role          VARCHAR2(20) NOT NULL,
  status        VARCHAR2(20) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_users PRIMARY KEY (user_id),
  CONSTRAINT uk_users_email UNIQUE (email),
  CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email)),
  CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN')),
  CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE TABLE categories (
  category_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  name        VARCHAR2(150) NOT NULL,
  slug        VARCHAR2(180) NOT NULL,
  description VARCHAR2(1000),
  status      VARCHAR2(20) NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_categories PRIMARY KEY (category_id),
  CONSTRAINT uk_categories_slug UNIQUE (slug),
  CONSTRAINT ck_categories_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE products (
  product_id    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  category_id   NUMBER(19) NOT NULL,
  sku           VARCHAR2(80) NOT NULL,
  name          VARCHAR2(255) NOT NULL,
  slug          VARCHAR2(300) NOT NULL,
  description   CLOB,
  base_price    NUMBER(15,2) NOT NULL,
  thumbnail_url VARCHAR2(500),
  status        VARCHAR2(20) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_products PRIMARY KEY (product_id),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
  CONSTRAINT uk_products_sku UNIQUE (sku),
  CONSTRAINT uk_products_slug UNIQUE (slug),
  CONSTRAINT ck_products_price CHECK (base_price >= 0),
  CONSTRAINT ck_products_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE product_inventory (
  product_id              NUMBER(19) NOT NULL,
  on_hand_quantity        NUMBER(10) NOT NULL,
  reserved_flash_quantity NUMBER(10) NOT NULL,
  version                 NUMBER(10) NOT NULL,
  updated_at              TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_product_inventory PRIMARY KEY (product_id),
  CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT ck_inventory_on_hand CHECK (on_hand_quantity >= 0),
  CONSTRAINT ck_inventory_reserved CHECK (reserved_flash_quantity >= 0),
  CONSTRAINT ck_inventory_res_le_on CHECK (reserved_flash_quantity <= on_hand_quantity)
);

CREATE TABLE carts (
  cart_id    NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  user_id    NUMBER(19) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_carts PRIMARY KEY (cart_id),
  CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (user_id),
  CONSTRAINT uk_carts_user UNIQUE (user_id)
);

CREATE TABLE cart_items (
  cart_item_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  cart_id      NUMBER(19) NOT NULL,
  product_id   NUMBER(19) NOT NULL,
  quantity     NUMBER(10) NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_cart_items PRIMARY KEY (cart_item_id),
  CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (cart_id),
  CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id),
  CONSTRAINT ck_cart_items_quantity CHECK (quantity > 0)
);

CREATE TABLE flash_sales (
  flash_sale_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  name          VARCHAR2(200) NOT NULL,
  description   VARCHAR2(1000),
  start_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  end_at        TIMESTAMP WITH TIME ZONE NOT NULL,
  status        VARCHAR2(20) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_flash_sales PRIMARY KEY (flash_sale_id),
  CONSTRAINT ck_flash_sales_time CHECK (end_at > start_at),
  CONSTRAINT ck_flash_sales_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'ACTIVE', 'ENDED', 'CANCELLED'))
);

CREATE TABLE flash_sale_configs (
  flash_sale_id              NUMBER(19) NOT NULL,
  max_quantity_per_user      NUMBER(10) DEFAULT 1 NOT NULL,
  reservation_timeout_seconds NUMBER(10) DEFAULT 60 NOT NULL,
  allow_cancel               CHAR(1) DEFAULT 'N' NOT NULL,
  created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_flash_sale_configs PRIMARY KEY (flash_sale_id),
  CONSTRAINT fk_fs_configs_sale FOREIGN KEY (flash_sale_id) REFERENCES flash_sales (flash_sale_id),
  CONSTRAINT ck_fs_configs_allow_cancel CHECK (allow_cancel IN ('Y', 'N'))
);

CREATE TABLE flash_sale_items (
  flash_sale_item_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  flash_sale_id      NUMBER(19) NOT NULL,
  product_id         NUMBER(19) NOT NULL,
  sale_price         NUMBER(15,2) NOT NULL,
  allocated_quantity NUMBER(10) NOT NULL,
  sold_quantity      NUMBER(10) NOT NULL,
  status             VARCHAR2(20) NOT NULL,
  created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT pk_flash_sale_items PRIMARY KEY (flash_sale_item_id),
  CONSTRAINT fk_fs_items_sale FOREIGN KEY (flash_sale_id) REFERENCES flash_sales (flash_sale_id),
  CONSTRAINT fk_fs_items_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT uk_fs_items_sale_product UNIQUE (flash_sale_id, product_id),
  CONSTRAINT ck_fs_items_price CHECK (sale_price >= 0),
  CONSTRAINT ck_fs_items_allocated CHECK (allocated_quantity > 0),
  CONSTRAINT ck_fs_items_sold CHECK (sold_quantity >= 0),
  CONSTRAINT ck_fs_items_sold_le_alloc CHECK (sold_quantity <= allocated_quantity),
  CONSTRAINT ck_fs_items_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE orders (
  order_id          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  order_code        VARCHAR2(40) NOT NULL,
  user_id           NUMBER(19) NOT NULL,
  order_type        VARCHAR2(20) NOT NULL,
  status            VARCHAR2(20) NOT NULL,
  subtotal          NUMBER(15,2) NOT NULL,
  discount_amount   NUMBER(15,2) DEFAULT 0 NOT NULL,
  total_amount      NUMBER(15,2) NOT NULL,
  recipient_name    VARCHAR2(150) NOT NULL,
  recipient_phone   VARCHAR2(30) NOT NULL,
  shipping_address  VARCHAR2(500) NOT NULL,
  idempotency_key   VARCHAR2(100) NOT NULL,
  created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
  cancelled_at      TIMESTAMP WITH TIME ZONE,
  CONSTRAINT pk_orders PRIMARY KEY (order_id),
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (user_id),
  CONSTRAINT uk_orders_code UNIQUE (order_code),
  CONSTRAINT uk_orders_idempotency UNIQUE (idempotency_key),
  CONSTRAINT ck_orders_type CHECK (order_type IN ('NORMAL', 'FLASH_SALE')),
  CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT ck_orders_subtotal CHECK (subtotal >= 0),
  CONSTRAINT ck_orders_discount CHECK (discount_amount >= 0 AND discount_amount <= subtotal),
  CONSTRAINT ck_orders_total CHECK (total_amount = subtotal - discount_amount),
  CONSTRAINT ck_orders_cancelled CHECK (
    (status = 'CANCELLED' AND cancelled_at IS NOT NULL) OR
    (status <> 'CANCELLED' AND cancelled_at IS NULL))
);

CREATE TABLE order_items (
  order_item_id     NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 INCREMENT BY 1),
  order_id          NUMBER(19) NOT NULL,
  product_id        NUMBER(19) NOT NULL,
  flash_sale_item_id NUMBER(19),
  product_name      VARCHAR2(255) NOT NULL,
  product_sku       VARCHAR2(80) NOT NULL,
  unit_price        NUMBER(15,2) NOT NULL,
  quantity          NUMBER(10) NOT NULL,
  line_total        NUMBER(15,2) NOT NULL,
  CONSTRAINT pk_order_items PRIMARY KEY (order_item_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (product_id),
  CONSTRAINT fk_order_items_fs_item FOREIGN KEY (flash_sale_item_id) REFERENCES flash_sale_items (flash_sale_item_id),
  CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
  CONSTRAINT ck_order_items_price CHECK (unit_price >= 0),
  CONSTRAINT ck_order_items_total CHECK (line_total >= 0),
  CONSTRAINT ck_order_items_line CHECK (line_total = unit_price * quantity)
);

